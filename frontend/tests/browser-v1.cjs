/* Product journeys added with the first-version UI: real API, source and database. */
const assert = require('node:assert/strict')
const path = require('node:path')
const {enterValue} = require('./browser-input.cjs')

async function run({playwright, browserType, executablePath, env, outputDirectory}) {
  const browser = await playwright[browserType].launch({headless:true, executablePath,...(process.env.QA_BROWSER_CHANNEL ? {channel:process.env.QA_BROWSER_CHANNEL} : {})})
  const context = await browser.newContext({baseURL:'http://127.0.0.1:5173', viewport:{width:1440,height:1000}})
  const employee = await browser.newContext({baseURL:'http://127.0.0.1:5173'})
  const page = await context.newPage()
  const errors=[]
  page.on('pageerror',()=>errors.push('runtime error'))
  const prefix='qa-v1-'+Date.now()
  let stage='setup'
  const call=async(client,route,body,method=body ? 'POST':'GET')=>{
    const response=await client.request.fetch('/api'+route,{method,data:body,headers:{'X-Requested-With':'antifraud-ui'}})
    assert.equal(response.status(),200,route)
    return response.json()
  }
  const shot=async(name)=>page.screenshot({path:path.join(outputDirectory,name+'.png'),mask:[page.locator('input[type="password"]:visible'),page.locator('.notice code:visible')],maskColor:'#e7eee9'})
  const compact=async(name)=>{
    for(const width of [900,390]){
      await page.setViewportSize({width,height:900})
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),name+' overflow at '+width)
      await shot(name+'-'+width)
    }
    await page.setViewportSize({width:1440,height:1000})
  }
  try {
    await call(employee,'/auth/login',{username:'employee',password:env.DIPLOMA_SEED_PASSWORD})
    const row=await call(employee,'/demo/requests',{title:prefix,amount:'125.50',recipient:'Учебный получатель',receipt:prefix,vendor:'QA',purchase_date:'2026-10-22'})
    await page.goto('/login')
    await page.getByLabel('Аккаунт',{exact:true}).selectOption('admin')
    await enterValue(page.getByLabel('Пароль',{exact:true}),env.DIPLOMA_SEED_PASSWORD)
    await page.getByRole('button',{name:'Войти',exact:true}).click()
    await page.getByRole('heading',{name:'Правила антифрода',exact:true}).waitFor()
    await call(context,'/admin/applications',{id:prefix,name:'QA: проверка источника и редактора',ttl_seconds:600,catalog:{move:{fields:{amount:{type:'number',required:true,source:'DB'},recipient:{type:'string',required:true,source:'DB'}}}}})
    const source={url:'postgresql+asyncpg://diploma_reader:'+env.DIPLOMA_READER_PASSWORD+'@postgres:5432/'+(env.POSTGRES_DB||'diploma'),table_name:'demo.requests',key_field:'id',allowed_fields:['amount','recipient'],mapping:{amount:'amount',recipient:'recipient'}}
    await call(context,'/admin/sources/'+prefix,source,'PUT')
    stage='source test without returning saved password'
    await page.getByRole('link',{name:'Приложения и источники',exact:true}).click()
    await page.getByRole('tab',{name:'Источники данных',exact:true}).click()
    await page.getByLabel('Приложение',{exact:true}).selectOption(prefix)
    await page.getByText('Загружаем настройки источника…',{exact:true}).waitFor({state:'hidden'})
    assert.equal(await page.getByLabel('Пароль подключения',{exact:true}).inputValue(),'')
    await enterValue(page.getByLabel('Ключ тестовой записи',{exact:true}),row.id)
    await page.getByRole('button',{name:'Проверить подключение и чтение',exact:true}).click()
    await page.getByText(/Подключение и права чтения проверены/).waitFor()
    await shot('source-tested')
    await compact('source')
    await enterValue(page.getByLabel('Ключ тестовой записи',{exact:true}),'missing-record')
    assert.equal(await page.getByText(/Подключение и права чтения проверены/).count(),0)
    await page.getByRole('button',{name:'Проверить подключение и чтение',exact:true}).click()
    await page.getByText('По ключу нужна ровно одна запись',{exact:true}).waitFor()
    assert.equal(await page.getByLabel('Ключ тестовой записи',{exact:true}).inputValue(),'missing-record')
    await page.getByRole('tab',{name:'Приложения',exact:true}).click()
    await page.getByRole('tab',{name:'Источники данных',exact:true}).click()
    assert.equal(await page.getByLabel('Ключ тестовой записи',{exact:true}).inputValue(),'missing-record')
    await enterValue(page.getByLabel('Ключ тестовой записи',{exact:true}),row.id)
    await page.getByRole('button',{name:'Сохранить источник',exact:true}).click()
    await page.getByText('Источник сохранён. Пароль не отображается повторно.',{exact:true}).waitFor()
    assert.equal(await page.getByLabel('Пароль подключения',{exact:true}).inputValue(),'')
    stage='compound editor and application-specific draft'
    await page.getByRole('link',{name:'Правила проверки',exact:true}).click()
    await page.getByRole('heading',{name:'Правила антифрода',exact:true}).waitFor()
    await page.getByText('Загружаем правила…',{exact:true}).waitFor({state:'hidden'})
    await page.getByLabel('Приложение',{exact:true}).selectOption(prefix)
    await page.getByText('0 включено',{exact:true}).waitFor()
    await page.getByRole('button',{name:'+ Новое правило',exact:true}).click()
    await enterValue(page.getByLabel('Название',{exact:true}),'Дробление суммы — проверка интерфейса')
    await page.getByLabel('Механизм',{exact:true}).selectOption('all')
    await page.getByRole('button',{name:'+ Условие',exact:true}).click()
    await page.getByLabel('Сравнение',{exact:true}).nth(0).selectOption('lt')
    await enterValue(page.getByLabel('Значение / порог',{exact:true}).nth(0),'10000')
    await page.getByLabel('Механизм',{exact:true}).nth(2).selectOption('aggregate')
    await page.getByLabel('Сравнение',{exact:true}).nth(1).selectOption('ge')
    await enterValue(page.getByLabel('Значение / порог',{exact:true}).nth(1),'10000')
    const group=page.getByRole('group',{name:'Группировка по полям',exact:true})
    await group.getByLabel('Сумма',{exact:true}).uncheck()
    await group.getByLabel('Получатель',{exact:true}).check()
    await page.getByLabel('Правило включено',{exact:true}).uncheck()
    await page.getByRole('tab',{name:'Шаблоны',exact:true}).click()
    await page.getByRole('tab',{name:'Правила',exact:true}).click()
    await page.getByLabel('Приложение',{exact:true}).selectOption('demo')
    await page.getByLabel('Приложение',{exact:true}).selectOption(prefix)
    assert.equal(await page.getByLabel('Название',{exact:true}).inputValue(),'Дробление суммы — проверка интерфейса')
    assert.equal(await page.getByLabel('Механизм',{exact:true}).count(),3)
    await page.getByText('Загружаем правила…',{exact:true}).waitFor({state:'hidden'})
    await shot('compound-editor')
    await compact('editor')
    const saved=page.waitForResponse(r=>r.url().endsWith('/api/admin/rules')&&r.request().method()==='POST')
    await page.getByRole('button',{name:'Сохранить правило',exact:true}).click()
    assert.equal((await saved).status(),200)
    await page.getByRole('row').filter({hasText:'Дробление суммы — проверка интерфейса'}).waitFor()
    stage='compatible journal filters and focus return'
    await page.getByRole('link',{name:'Журнал решений',exact:true}).click()
    await page.getByRole('button',{name:'Подробнее',exact:true}).first().waitFor()
    const opener=page.getByRole('button',{name:'Подробнее',exact:true}).first()
    await opener.click()
    await page.getByRole('heading',{name:'История решения',exact:true}).waitFor()
    await page.getByRole('button',{name:'Закрыть панель',exact:true}).press('Escape')
    assert(await opener.evaluate(button=>document.activeElement===button))
    assert.equal(await page.getByLabel('Приложение',{exact:true}).count(),1,'Application filter label')
    assert.equal(await page.locator('option[value="'+prefix+'"]').count(),1,'Application metadata option')
    await page.getByLabel('Приложение',{exact:true}).selectOption(prefix)
    assert.equal(await page.getByLabel('Действие',{exact:true}).locator('option').count(),2)
    await page.getByRole('button',{name:'Применить фильтры',exact:true}).click()
    await page.getByText('По этим фильтрам проверки не найдены.',{exact:true}).waitFor()
    await shot('journal-empty')
    await compact('journal')
    assert.equal(errors.length,0)
    return {browser:browserType,version:browser.version(),real_source_test:true,saved_password_reused:true,source_test_error_retains_input:true,source_tab_retains_draft:true,stale_test_result_hidden:true,compound_editor:true,per_application_draft:true,compatible_journal_filters:true,empty_state:true,escape_restores_focus:true,viewports:[1440,900,390],javascript_errors:errors.length}
  } catch(error) {await shot('v1-failure').catch(()=>{});throw new Error('Browser QA failed at '+stage+': '+error.message.split('\n')[0])}
  finally {await employee.close();await browser.close()}
}
module.exports={run}
